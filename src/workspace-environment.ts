import { homedir } from "node:os";
import { shellEscape, formatEnvAssignment } from "./shell.js";

export interface EnvironmentBindings {
  env?: Record<string, string>;
  env_from_files?: Record<string, string>;
}

export function expandEnvironmentPath(path: string): string {
  return path.startsWith("~/") ? `${homedir()}/${path.slice(2)}` : path;
}

// Merge the two kinds of binding together: a later literal replaces a file,
// and a later file replaces a literal, for the same variable.
export function mergeEnvironment(...layers: (EnvironmentBindings | undefined | null)[]): Required<EnvironmentBindings> {
  const env: Record<string, string> = {};
  const env_from_files: Record<string, string> = {};
  for (const layer of layers) {
    for (const [name, value] of Object.entries(layer?.env ?? {})) {
      delete env_from_files[name];
      env[name] = value;
    }
    for (const [name, value] of Object.entries(layer?.env_from_files ?? {})) {
      delete env[name];
      env_from_files[name] = value;
    }
  }
  return { env, env_from_files };
}

export function validateEnvironmentName(name: string): void {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) || name.startsWith("_pitch_")) {
    throw new Error(`Invalid environment variable name: ${name}`);
  }
}

export function environmentScript(
  bindings: EnvironmentBindings,
  file: string,
  workspaceName: string,
  privateNames: string[] = [],
): string {
  const resolved = mergeEnvironment(bindings, { env: {
    PITCH_WORKSPACE_ENV_FILE: file,
    PITCH_WORKSPACE_NAME: workspaceName,
  } });
  const names = [...Object.keys(resolved.env), ...Object.keys(resolved.env_from_files)];
  [...names, ...privateNames].forEach(validateEnvironmentName);
  const lines = ["# Generated by Pitch. Source this file; do not edit.", "_pitch_apply_environment() {"];
  // Read every required file before changing the caller's environment.
  const files = Object.entries(resolved.env_from_files);
  files.forEach(([name, path], i) => {
    lines.push(`  local _pitch_value_${i}`,
      `  _pitch_value_${i}=$(cat -- ${shellEscape(expandEnvironmentPath(path))}) || {`,
      `    printf '%s\\n' ${shellEscape(`pitch: cannot load environment file for ${name}`)} >&2`,
      "    return 1", "  }");
  });
  lines.push("  local _pitch_old", "  for _pitch_old in $(printf '%s' \"${PITCH_MANAGED_ENV_NAMES-}\"); do",
    "    case \"$_pitch_old\" in ''|[0-9]*|*[!A-Za-z0-9_]*) continue ;; esac",
    "    unset \"$_pitch_old\"", "  done");
  for (const name of privateNames) lines.push(`  unset ${name}`);
  for (const [name, value] of Object.entries(resolved.env)) {
    lines.push(`  export ${formatEnvAssignment(name, value)}`);
  }
  files.forEach(([name], i) => lines.push(`  export ${name}="$_pitch_value_${i}"`));
  lines.push(`  export PITCH_MANAGED_ENV_NAMES=${shellEscape(names.join(" "))}`,
    "}", "_pitch_apply_environment", "");
  return lines.join("\n");
}

export function wrapWorkspaceEnvironment(command: string[], file?: string): string[] {
  return file ? ["/bin/sh", "-c", '. "$1" && shift && exec "$@"', "pitch-environment", file, ...command] : command;
}
